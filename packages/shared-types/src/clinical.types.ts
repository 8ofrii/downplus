/**
 * @module clinical.types
 * @description Clinical data shape interfaces used for medical data,
 * AI context anonymization, and doctor matching.
 */

// ---------------------------------------------------------------------------
// Comorbidity
// ---------------------------------------------------------------------------

/**
 * String literal union of common comorbidities associated with Down Syndrome.
 * Extend this union as the clinical vocabulary grows.
 */
export type Comorbidity =
  | 'congenital_heart_defect'
  | 'hypothyroidism'
  | 'celiac_disease'
  | 'hearing_loss'
  | 'vision_problems'
  | 'obstructive_sleep_apnea'
  | 'atlantoaxial_instability'
  | 'leukemia'
  | 'hirschsprung_disease'
  | 'autism_spectrum_disorder'
  | 'epilepsy'
  | 'obesity'
  | (string & {}); // allow arbitrary strings while preserving autocomplete

// ---------------------------------------------------------------------------
// Medication
// ---------------------------------------------------------------------------

/** A single medication entry. */
export interface Medication {
  /** Drug / active-ingredient name. */
  drug: string;
  /** Dosage amount and unit (e.g. "50 mg"). */
  dosage: string;
  /** Frequency of administration (e.g. "twice daily"). */
  frequency: string;
}

// ---------------------------------------------------------------------------
// AI Generated Summary
// ---------------------------------------------------------------------------

/** Summary generated by the AI pipeline after processing uploaded documents. */
export interface AiGeneratedSummary {
  /** Conditions extracted from medical documents. */
  extracted_conditions: string[];
  /** Medications currently prescribed. */
  current_medications: Medication[];
  /** Strengths identified from therapy / milestone data. */
  identified_strengths: string[];
  /** Top clinical needs ranked by priority. */
  priority_clinical_needs: string[];
  /** Optional growth metrics keyed by metric name (e.g. "weight_kg"). */
  growth_metrics?: Record<string, number>;
}

// ---------------------------------------------------------------------------
// Anonymized Context
// ---------------------------------------------------------------------------

/**
 * A privacy-safe context payload sent to external AI services.
 * No PII is included — only clinically relevant information.
 */
export interface AnonymizedContext {
  /** Child's age in months. */
  age_months: number;
  /** Biological gender. */
  gender: string;
  /** Primary diagnosis description. */
  primary_diagnosis: string;
  /** Karyotype classification (e.g. "Trisomy 21 - Non-disjunction"). */
  karyotype: string;
  /** List of comorbidity identifiers. */
  comorbidities: string[];
  /** Current medications. */
  current_medications: Medication[];
  /** Free-text summary of milestone progress. */
  milestone_summary: string;
}

// ---------------------------------------------------------------------------
// Doctor Match Score
// ---------------------------------------------------------------------------

/** Breakdown of how well a doctor matches a given case. */
export interface DoctorMatchScore {
  /** 0-1 score for specialty relevance. */
  specialty_match: number;
  /** 0-1 score for geographic proximity. */
  location_proximity: number;
  /** 0-1 score for Down Syndrome clinical experience. */
  ds_experience: number;
  /** 0-1 aggregate rating from reviews. */
  rating: number;
  /** Weighted total score. */
  total: number;
}
